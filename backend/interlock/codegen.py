"""Generate a readable, modern Python controller from the parsed legacy program.

Cryptic tags become descriptive names (from the glossary), each rule block
carries its plain-English description and original line numbers, and each
scan reports which rules fired.
"""
from __future__ import annotations

import textwrap

from .st_parser import Assign, If, Program


def _lit(v) -> str:
    return repr(v)


class CodeGen:
    def __init__(self, prog: Program, glossary: dict, extraction: dict, source_name: str):
        self.prog = prog
        self.g = glossary
        self.ex = extraction
        self.source_name = source_name
        self.rule_by_line = {r["trigger_line"]: r for r in extraction["rules"]}
        self.counter_by_line = {c["line"]: (k, c) for k, c in extraction["counters"].items()}
        self.derived_by_line = {d["line"]: d for d in extraction["derived"]}
        self.names = {d.name: glossary.get(d.name, {}).get("name", d.name.lower()) for d in prog.decls}
        self.kind = {d.name: d.block for d in prog.decls}
        self.lines: list[str] = []

    # --- expressions
    def ref(self, v: str) -> str:
        return self.names[v] if self.kind[v] == "input" else f"self.{self.names[v]}"

    def py(self, e) -> str:
        k = e[0]
        if k in ("num", "bool"):
            return _lit(e[1])
        if k == "var":
            return self.ref(e[1])
        if k == "un":
            return f"(not {self.py(e[2])})" if e[1] == "NOT" else f"(-{self.py(e[2])})"
        op = {"AND": "and", "OR": "or", "=": "==", "<>": "!="}.get(e[1], e[1])
        return f"({self.py(e[2])} {op} {self.py(e[3])})"

    def strip(self, e) -> str:
        """Drop one pair of outer parentheses for readability."""
        s = self.py(e)
        return s[1:-1] if s.startswith("(") and s.endswith(")") and e[0] in ("bin", "un") else s

    # --- emit
    def out(self, indent: int, text: str = ""):
        self.lines.append(("    " * indent + text) if text else "")

    def comment(self, indent: int, text: str):
        pad = "    " * indent + "# "
        for ln in textwrap.wrap(text, width=96 - len(pad)):
            self.lines.append(pad + ln)

    def stmts(self, stmts, indent: int):
        for s in stmts:
            if isinstance(s, Assign):
                self.assign(s, indent)
            else:
                self.if_stmt(s, indent)

    def assign(self, s: Assign, indent: int):
        d = self.derived_by_line.get(s.line)
        if d:
            self.comment(indent, d["english"])
        rule = self.rule_by_line.get(s.line)
        if rule and rule["kind"] == "follows":
            self.comment(indent, f"{rule['id']} (original line {s.line}): {rule['english']}")
        self.out(indent, f"{self.ref(s.name)} = {self.strip(s.expr)}")
        if rule and rule["kind"] == "follows":
            self.out(indent, f"if {self.ref(s.name)}:")
            self.out(indent + 1, f"fired.append({rule['id']!r})")

    def if_stmt(self, s: If, indent: int):
        counter = self.counter_by_line.get(s.line)
        if counter:
            self.comment(indent, f"Counts consecutive scans while {counter[1]['cond']} "
                                 f"(original line {s.line}).")
        for i, b in enumerate(s.branches):
            if b.cond is None:
                self.out(indent, "else:")
            else:
                self.out(indent, f"{'if' if i == 0 else 'elif'} {self.strip(b.cond)}:")
            rule = self.rule_by_line.get(b.line)
            if rule:
                lo, hi = rule["lines"]
                self.comment(indent + 1, f"{rule['id']} (original lines {lo}-{hi}): {rule['english']}")
                self.out(indent + 1, f"fired.append({rule['id']!r})")
            if not b.body:
                self.out(indent + 1, "pass")
            self.stmts(b.body, indent + 1)

    def generate(self) -> str:
        p = self.prog
        inputs = [d for d in p.decls if d.block == "input"]
        outputs = [d for d in p.decls if d.block == "output"]
        state = [d for d in p.decls if d.block != "input"]
        self.out(0, '"""Chilled-water plant sequencer (generated by Interlock).')
        self.out(0)
        self.out(0, f"Rewritten from {self.source_name}. Names come from the reviewed glossary, every")
        self.out(0, "rule is annotated with its plain-English meaning and original line numbers, and")
        self.out(0, "step() reports which rules fired on each scan. Behaviour is checked against the")
        self.out(0, "original by the parity test; do not edit by hand.")
        self.out(0, '"""')
        self.out(0)
        self.out(0, "from __future__ import annotations")
        self.out(0)
        self.out(0)
        self.out(0, "class ChwSequencer:")
        self.out(1, f'SCAN_SECONDS = {self.ex.get("scan_s", 1.0)!r}')
        self.out(1, f"INPUTS = {tuple(self.names[d.name] for d in inputs)!r}".replace("', '", "',\n        '") .replace("('", "(\n        '").replace("',)", "',\n    )").replace("')", "',\n    )"))
        self.out(1, f"OUTPUTS = {tuple(self.names[d.name] for d in outputs)!r}".replace("', '", "',\n        '").replace("('", "(\n        '").replace("',)", "',\n    )").replace("')", "',\n    )"))
        self.out(0)
        self.out(1, "def __init__(self) -> None:")
        self.out(2, "self.reset()")
        self.out(0)
        self.out(1, "def reset(self) -> None:")
        for d in state:
            init = d.init if d.init is not None else (False if d.type == "BOOL" else 0 if d.type == "INT" else 0.0)
            self.out(2, f"self.{self.names[d.name]} = {_lit(init)}")
        self.out(0)
        self.out(1, "def step(")
        self.out(2, "self,")
        self.out(2, "*,")
        for d in inputs:
            self.out(2, f"{self.names[d.name]}: {'bool' if d.type == 'BOOL' else 'float'},")
        self.out(1, ") -> tuple[dict, list[str]]:")
        self.out(2, "fired: list[str] = []")
        self.stmts(p.body, 2)
        self.out(0)
        self.out(2, "outputs = {")
        for d in outputs:
            self.out(3, f'"{self.names[d.name]}": self.{self.names[d.name]},')
        self.out(2, "}")
        self.out(2, "return outputs, fired")
        return "\n".join(self.lines) + "\n"


def generate(prog: Program, glossary: dict, extraction: dict, source_name: str = "chw_sequencer.st") -> str:
    return CodeGen(prog, glossary, extraction, source_name).generate()


def load_class(source: str):
    ns: dict = {}
    exec(compile(source, "<modern_sequencer>", "exec"), ns)
    return ns["ChwSequencer"]
