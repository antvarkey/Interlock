import { useEffect, useRef, useState } from "react";
import { PageHead, Trace } from "../components/Bits.jsx";
import { api } from "../lib/api.js";
import { lineSpan } from "../lib/format.js";

export default function RulesView({ st, sel, setSel }) {
  const [mode, setMode] = useState("legacy");
  const [q, setQ] = useState("");
  const [answer, setAnswer] = useState(null);
  const srcRef = useRef(null);
  const r = st.rules.find((x) => x.id === sel) || st.rules[0];
  const g = st.glossary;

  const mism = st.findings.filter((f) => f.kind === "runbook_mismatch").length;
  const dead = st.findings.filter((f) => f.kind === "dead_input").length;
  const tickets = new Set(st.rules.flatMap((x) => x.tickets.map((t) => t.id))).size;

  useEffect(() => {
    const c = srcRef.current, h = c?.querySelector(".hl");
    if (c) c.scrollTop = h && mode === "legacy" ? Math.max(0, h.offsetTop - 80) : 0;
  }, [sel, mode]);

  const ask = async () => {
    if (!q.trim()) return;
    setAnswer("Thinking…");
    try { setAnswer((await api.ask(q)).answer); } catch { setAnswer("Could not reach the server."); }
  };

  const src = mode === "legacy" ? st.legacy_source : st.modern_source;
  const tag = (v) => (
    <div className="tag" key={v}><code>{v}</code><span>{g[v]?.desc || g[v]?.name || ""}</span></div>
  );

  return (
    <>
      <PageHead n="02" eyebrow="Rule extraction · chw_sequencer.st (2004)" dim="Decades-old control code." title="Read as plain-English rules."
        right={<div className="row" style={{ width: 460 }}>
          <input type="text" style={{ flex: 1 }} value={q} onChange={(e) => setQ(e.target.value)} onKeyDown={(e) => e.key === "Enter" && ask()} placeholder="Ask: why does cooling stop at job start?" aria-label="Ask about the rules" />
          <button className="btn" onClick={ask}>Ask</button>
        </div>}>
        Every rule is generated by a parser, not guessed, and traced to the exact lines it came from. Interlock also checks the code against the runbook and the point list.
      </PageHead>
      {answer && <div className="card" style={{ marginBottom: 16, whiteSpace: "pre-wrap" }}><div className="eyebrow" style={{ marginBottom: 8 }}>Ask Interlock · answers only from extracted rules, findings and tickets</div>{answer}</div>}

      <div className="summary">
        <div><b>{st.rules.length}</b><span>rules extracted, each with source lines</span></div>
        <div><b style={{ color: "var(--warn)" }}>{mism}</b><span>places where the runbook disagrees with the code</span></div>
        <div><b>{dead}</b><span>dead rule tied to a retired sensor tag</span></div>
        <div><b style={{ color: "var(--accent)" }}>{tickets}</b><span>“cause unknown” incidents now explained</span></div>
      </div>

      <div className="rules-grid">
        <div id="rlist">
          {st.rules.map((x) => (
            <button key={x.id} className="rcard" data-r={x.id} aria-pressed={x.id === r.id} onClick={() => { setSel(x.id); setMode("legacy"); }}>
              <div className="h">
                <Trace id={x.id} lines={x.lines} />
                {x.protective && <span className="chip crit">Interrupts cooling or load</span>}
                {x.findings.length > 0 && <span className="chip warn">{x.findings.length} finding{x.findings.length > 1 ? "s" : ""}</span>}
                {x.tickets.length > 0 && <span className="chip accent">{x.tickets.length} incidents</span>}
              </div>
              <p>{x.english}</p>
            </button>
          ))}
        </div>

        <div className="stack">
          <div className="card" id="detail">
            <div className="row" style={{ marginBottom: 14 }}>
              <span className="eyebrow">Rule {r.id} · in plain English</span><span className="sp" />
              <span className="chip mono">{lineSpan(r.lines)}</span>
            </div>
            <p className="english">{r.english}</p>
            {r.interrupts.length > 0 && <p style={{ marginTop: 10, color: "var(--crit)" }}>Effect: {r.interrupts.join("; ")}.</p>}
            <div className="io">
              <div><div className="eyebrow" style={{ marginBottom: 6 }}>Reads</div>{r.reads.length ? r.reads.map(tag) : <p className="faint small">Nothing</p>}</div>
              <div><div className="eyebrow" style={{ marginBottom: 6 }}>Writes</div>{r.writes.map(tag)}</div>
            </div>
          </div>

          <div className="card">
            <div className="row" style={{ marginBottom: 12 }}>
              <div className="seg" role="group" aria-label="Which code to show">
                <button aria-pressed={mode === "legacy"} onClick={() => setMode("legacy")}>Original · Structured Text</button>
                <button aria-pressed={mode === "modern"} onClick={() => setMode("modern")}>Rewrite · Python</button>
              </div>
              <span className="sp" />
              <span className="faint small mono">{mode === "legacy" ? "legacy/chw_sequencer.st" : "generated/modern_sequencer.py"}</span>
            </div>
            <div className="code" ref={srcRef} id="src" tabIndex={0}>
              {src.split("\n").map((ln, k) => (
                <div key={k} className={mode === "legacy" && k + 1 >= r.lines[0] && k + 1 <= r.lines[1] ? "hl" : ""}><i>{k + 1}</i>{ln || " "}</div>
              ))}
            </div>
          </div>

          {r.findings.length > 0 && (
            <div className="card">
              <div className="eyebrow">Needs a human decision</div>
              {r.findings.map((f) => <div key={f.text} className={`finding ${f.kind === "dead_input" ? "dead" : ""}`}><b>{f.label}.</b> {f.text}</div>)}
            </div>
          )}
          {r.tickets.length > 0 && (
            <div className="card">
              <div className="eyebrow" style={{ marginBottom: 6 }}>Past incidents this rule explains</div>
              {r.tickets.map((t) => <div key={t.id} className="ticket"><span className="id">{t.id}</span><span className="faint mono small">{t.date}</span><div className="muted" style={{ marginTop: 3 }}>{t.text}</div></div>)}
            </div>
          )}
          {r.mitigations.length > 0 && (
            <div className="card">
              <div className="eyebrow" style={{ marginBottom: 6 }}>Known mitigations · verified in simulation before they are offered</div>
              {r.mitigations.map((x) => <div key={x.id} className="ticket"><b>{x.title}.</b> <span className="muted">{x.how}</span></div>)}
            </div>
          )}
        </div>
      </div>
    </>
  );
}
